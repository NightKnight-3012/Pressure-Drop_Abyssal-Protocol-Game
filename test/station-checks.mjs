import assert from "node:assert/strict";
import * as THREE from "three";
import {createStationDetail,ROOM_LIGHT_COLORS} from "../client/src/station-detail.js";
import {createPowerUnit} from "../client/src/power-unit.js";
import {createLightScattering} from "../client/src/light-scattering.js";
import {addFloodFlow} from "../client/src/flood-flow.js";
import {CRATES,ROOM_IDS,STATIONS,collides} from "../shared/layout.js";
import {createGame,snapshotGame} from "../server/game.js";
let checks=0;
const check=(name,value)=>{assert.ok(value,name);checks++;console.log(`PASS ${name}`);};
const scene=new THREE.Scene(), detail=createStationDetail(scene);
let meshes=0,vertices=0,finite=true,lights=0;
detail.root.traverse(o=>{if(o.isMesh||o.isPoints)meshes++;if(o.isLight)lights++;if(o.geometry){vertices+=o.geometry.attributes.position.count;for(const name of ['position','normal','uv'])if(o.geometry.attributes[name])finite&&=o.geometry.attributes[name].array.every(Number.isFinite);}});
check("station identity stays within an eighteen-draw budget",meshes<=18);
check("station identity keeps geometry below fifty thousand vertices",vertices<50000);
check("decorative geometry has finite positions, normals and UVs",finite);
check("room dressing adds no lights or shadow rendering passes",lights===0);
check("furniture has five different room-specific identities",new Set(detail.physicalBounds.map(b=>b.kind)).size===5);
for(const {kind,crate,bounds} of detail.physicalBounds){const c=CRATES[crate];check(`${kind} fits the existing solid footprint`,bounds.min.x>=c.cx-c.w/2-.00001 && bounds.max.x<=c.cx+c.w/2+.00001 && bounds.min.z>=c.cz-c.d/2-.00001 && bounds.max.z<=c.cz+c.d/2+.00001);}
check("storage chests preserve the original window sightlines",detail.physicalBounds.filter(p=>p.crate===1||p.crate===2).every(p=>p.bounds.max.y<=CRATES[p.crate].h+.00001));
check("room lighting uses separate restrained color identities",new Set(ROOM_LIGHT_COLORS).size===5);
const state={power:false,rooms:Object.fromEntries(ROOM_IDS.map(r=>[r,{impacts:0}])),breaches:[]};
detail.update(state,{time:0});check("undamaged station windows have no strike scars",[...detail.damage.values()].every(m=>!m.visible));
state.rooms.control.impacts=2;detail.update(state,{time:1});
check("hull damage appears only on the struck room's windows",detail.damage.get('control').visible && [...detail.damage].filter(([id])=>id!=='control').every(([,m])=>!m.visible));
check("strike scars retain the view through the window",detail.damage.get('control').material.transparent && detail.damage.get('control').material.opacity<.4);
const waterScene=new THREE.Scene(), water=addFloodFlow(waterScene);
const dryRooms=Object.fromEntries(ROOM_IDS.map(r=>[r,{flood:0,closed:false}]));
const breach={id:'b1',room:'engineering',x:9.5,z:-5,severity:1.3};
const leak={rooms:dryRooms,hub:0,breaches:[breach]};
const p=water.mesh.geometry.attributes.position;
const count=()=>water.mesh.geometry.drawRange.count;
water.update(leak,2,false,'balanced');
check("a breach creates a continuous jet from the repair seam",water.mesh.visible && count()===144 && p.getY(0)<.2 && p.array.some((y,i)=>i%3===1&&y>1.2));
const version=p.version;
water.update(leak,3,true,'balanced');
check("reduced effects freeze the water texture and reuse the geometry",p.version===version && water.mesh.material.uniforms.time.value===0);
water.update({...leak,breaches:[{...breach}]},3.5,false,'balanced',.01);
check("identical flood snapshots reuse geometry while the water surface moves",p.version===version && water.mesh.position.y===.01);
water.update({...leak,breaches:[{...breach,clampedIn:2}]},4,true,'balanced');
check("a temporary clamp stops the jet immediately",count()===0);
water.update({...leak,breaches:[]},4,true,'balanced');
check("patched breaches remove flow immediately",!water.mesh.visible);
const rooms={...dryRooms,engineering:{flood:1,closed:false}};
water.update({rooms,hub:.3,breaches:[]},5,false,'balanced');
check("open bulkheads carry water from the higher level toward the lower level",count()>0 && p.getY(0)>p.getY(count()-1));
water.update({rooms:{...rooms,engineering:{flood:1,closed:true}},hub:0,breaches:[]},6,false,'balanced');
check("a closed bulkhead has no cross-door flow",!water.mesh.visible);
water.mesh.geometry.dispose();water.mesh.material.dispose();
const camera=new THREE.PerspectiveCamera();camera.position.set(-5,1.65,-5);
detail.update(state,{time:10,camera,flashlightOn:true,quality:'low'});check("beam particles use the selected quality budget",detail.dust.visible && detail.dust.geometry.drawRange.count===60);
detail.update(state,{time:11,camera,flashlightOn:false});check("switching off the lamp hides beam particles",!detail.dust.visible);
detail.update(state,{time:12,camera,flashlightOn:true,reducedEffects:true});check("reduced effects disable beam particle motion",!detail.dust.visible);
const game=createGame({players:[],seed:4});game.rooms.control.impacts=3;
check("impact history survives authoritative late-join snapshots",snapshotGame(game,[]).rooms.control.impacts===3);
check("replaying starts with undamaged windows",snapshotGame(createGame({players:[],seed:5}),[]).rooms.control.impacts===0);
check("all interaction points are still in the shared layout",Object.values(STATIONS).every(s=>Number.isFinite(s.x)&&Number.isFinite(s.z)));
check("central traversal remains clear of new solids",!collides(0,0) && !collides(1,1) && !collides(-1,-1));
detail.dispose();check("station detail disposal removes its scene objects",scene.children.length===0);
const status=new THREE.MeshStandardMaterial(),unit=createPowerUnit(status,null),unitBox=new THREE.Box3().setFromObject(unit);
check('power assembly stays inside the existing wall panel footprint',unitBox.min.x>=-.501 && unitBox.max.x<=.501 && unitBox.min.z>=-.15 && unitBox.max.z<=.301);
check('power assembly uses four batches and no new lights',unit.children.length===4 && unit.children.every(m=>m.isMesh));
check('power assembly shares the real repair status indicator',unit.children.some(m=>m.material===status));
unit.traverse(o=>{o.geometry?.dispose();o.material?.dispose();});
const effects=createLightScattering(scene);
const visible=()=>scene.children.filter(mesh=>mesh.visible).length;
const view={camera,flashlightOn:true};
effects.update(view,'balanced');check('all window shafts and floor spill use two batches',visible()===2);
const windowShafts=scene.getObjectByName('Volumetric window shafts');
check('window shafts have enclosed geometry and a bounded sampling budget',windowShafts.geometry.index.count===8*36 && windowShafts.material.uniforms.samples.value===5);
effects.update(view,'high');
check('High adds samples without adding draws',visible()===2 && windowShafts.material.uniforms.samples.value===8);
view.outside=true;effects.update(view,'high');check('only the suit beam draws during EVA',visible()===1);
view.flashlightOn=false;effects.update(view,'high');check('switching off the torch clears its beam',visible()===0);
view.flashlightOn=true;effects.update(view,'low');check('Low skips all scattering draws',visible()===0);
view.reducedEffects=true;effects.update(view,'balanced');check('Reduced effects skips scattering on Balanced',visible()===0);
Object.assign(view,{outside:false,underwater:true,reducedEffects:false});
effects.update(view,'balanced');check('a flooded compartment also shows the lit suit beam',visible()===3);
console.log(`${checks}/${checks} station checks passed (${meshes} draws, ${vertices} vertices).`);
